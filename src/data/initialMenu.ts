export function resolveDishImage(item: MenuItem): string {
  if (item.image_url && item.image_url.trim()) return item.image_url;
  const match = INITIAL_MENU_ITEMS.find(
    (m) => m.name.toLowerCase() === item.name.toLowerCase()
  );
  return match?.image_url || '/assets/menu/rendang-daging.jpg';
}
